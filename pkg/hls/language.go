// LanguageName maps an ISO 639 language code to a human-readable name. It
// covers ISO 639-1 two-letter codes plus the ISO 639-2/B bibliographic codes
// ffprobe commonly emits (cze, ger, gre, fre, dut, baq, may, rum, chi, ...).
